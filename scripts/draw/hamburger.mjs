import { bench, ellipse } from './lib.mjs';

// ================================================================ 햄버거 — 참조 없음(직접 디자인), 웃는 얼굴이 있는 햄버거
// 첫 단계에 위아래 빵을 함께 그려 크기를 정하고(위 빵만으로는 높이가 모자람), 사이에 속을 채웁니다.
// 양상추·치즈는 앞 획에 양 끝이 붙는 열린 획이고, 고기는 치즈에서 내려와 아래 빵에 닿는 양옆 둥근 끝만 긋습니다.
// 고기 아랫선은 아래 빵 윗선이 대신합니다.
export default function draw() {
  const b = bench();
  const top = b.closed('top', [
    [60, 214], [64, 178], [86, 140], [130, 112], [200, 100], [270, 112],
    [314, 140], [336, 178], [340, 214], [326, 226], [200, 230], [74, 226],
  ]);
  const bottom = b.closed('bottom', [
    [56, 346], [130, 342], [200, 341], [270, 342], [344, 346], [348, 370],
    [334, 394], [290, 406], [200, 410], [110, 406], [66, 394], [52, 370],
  ]);
  b.step('위아래 빵', '종이 위쪽에 둥근 빵을, 그 아래에 납작한 빵을 그려요.', top, bottom);

  const eyeL = b.closed('eyeL', ellipse(166, 182, 8, 10));
  const eyeR = b.closed('eyeR', ellipse(234, 182, 8, 10));
  b.step('눈 두 개', '위 빵 아래쪽에 까만 눈을 두 개 그려요.', eyeL, eyeR);

  const mouth = b.closed('mouth', [[184, 196], [200, 198], [216, 196], [212, 208], [200, 214], [188, 208]], 0.8);
  b.step('웃는 입', '두 눈 사이 아래에 작게 웃는 입을 그려요.', mouth);

  // 깨 — 길쭉한 작은 동그라미를 이리저리 기울여서
  const seeds = [[132, 144, -0.6], [174, 122, -0.25], [226, 122, 0.25], [268, 144, 0.6]]
    .map(([x, y, r], i) => b.closed(`sesame${i}`, ellipse(x, y, 9, 5, 8, r)));
  b.step('깨', '위 빵 꼭대기에 길쭉한 깨를 여기저기 그려요.', ...seeds);

  // 양상추 — 위 빵 아래 양 끝에서 나와 아래로 물결칩니다.
  const lettuce = b.open('lettuce', [
    [66, 220], [46, 238], [70, 256], [96, 244], [122, 260], [148, 246], [174, 260],
    [200, 248], [226, 260], [252, 246], [278, 260], [304, 244], [330, 256], [354, 238], [334, 220],
  ], ['top', 'top'], 0.9);
  b.step('양상추', '위 빵 아래에 꼬불꼬불한 양상추를 그려요.', lettuce);

  // 치즈 — 양쪽 모서리가 삐죽 나오고 가운데로 녹아 흐릅니다.
  const cheese = b.open('cheese', [
    [80, 256], [50, 284], [90, 282], [112, 284], [116, 306], [130, 310], [140, 286],
    [190, 282], [226, 284], [232, 312], [246, 316], [254, 286], [310, 282], [350, 284], [320, 256],
  ], ['lettuce', 'lettuce'], 0.7);
  b.step('녹은 치즈', '양상추 아래에 녹아서 흘러내리는 치즈를 그려요.', cheese);

  // 고기 — 치즈 모서리 아래에서 둥글게 내려와 아래 빵에 닿습니다.
  const pattyL = b.open('pattyL', [[62, 286], [46, 296], [50, 312], [42, 324], [50, 338], [64, 344]], ['cheese', 'bottom']);
  const pattyR = b.open('pattyR', [[338, 286], [354, 296], [350, 312], [358, 324], [350, 338], [336, 344]], ['cheese', 'bottom']);
  b.step('두툼한 고기', '치즈 아래 양옆에 고기의 둥근 끝을 그려요.', pattyL, pattyR);

  const cheekL = b.closed('cheekL', ellipse(134, 204, 14, 8));
  const cheekR = b.closed('cheekR', ellipse(266, 204, 14, 8));
  b.step('볼 두 개', '입 양옆에 발그레한 볼을 동그랗게 그려요.', cheekL, cheekR);

  // 꼭대기 깃발 — 깃발을 먼저 그리고 빵에서 깃발까지 막대를 긋습니다.
  const flag = b.closed('flag', [[206, 34], [232, 40], [252, 48], [232, 56], [206, 62]], 0.7);
  const pick = b.open('pick', [[200, 101], [200, 70], [204, 36]], ['top', 'flag']);
  b.step('깃발', '빵 꼭대기에 막대를 꽂고 작은 깃발을 달아요.', flag, pick);

  return {
    id: 'hamburger', title: '햄버거', theme: 'food', difficulty: 'normal', grades: ['middle'],
    paper: 'portrait', viewBox: '0 0 400 500',
    setupSay: '종이를 세로로 놓고, 가운데에 손바닥만큼 크게 그릴 거예요.',
    coloringSeconds: 150, steps: b.steps, keywords: ['음식', '햄버거', '간식'],
  };
}
