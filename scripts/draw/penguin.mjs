import { bench, ellipse } from './lib.mjs';

// ================================================================ 펭귄 — 참조 없음(직접 디자인), 앞을 봅니다
// 첫 획은 머리와 몸이 하나인 통통한 달걀 몸. 얼굴의 흰 무늬는 닫힌 하트 모양이고,
// 목도리는 몸 테두리에 양 끝이 붙는 줄 두 개, 흰 배는 목도리 아래에서 내려와 목도리 끝자락에 붙습니다.
export default function draw() {
  const b = bench();
  const body = b.closed('body', [
    [200, 76], [254, 86], [294, 120], [312, 176], [320, 236], [336, 296],
    [344, 354], [326, 400], [280, 426], [200, 434], [120, 426], [74, 400],
    [56, 354], [64, 296], [80, 236], [88, 176], [106, 120], [146, 86],
  ]);
  b.step('통통한 몸', '종이 가운데에 위가 둥근 통통한 몸을 크게 그려요.', body);

  // 얼굴 흰 무늬 — 위 가운데가 살짝 들어간 하트 모양
  const mask = b.closed('mask', [
    [200, 138], [222, 118], [250, 112], [274, 126], [286, 160], [282, 198],
    [262, 230], [230, 246], [200, 250], [170, 246], [138, 230], [118, 198],
    [114, 160], [126, 126], [150, 112], [178, 118],
  ]);
  b.step('얼굴 무늬', '몸 위쪽에 하트 같은 얼굴 무늬를 그려요.', mask);

  const eyeL = b.closed('eyeL', ellipse(162, 176, 8, 10));
  const eyeR = b.closed('eyeR', ellipse(238, 176, 8, 10));
  b.step('눈 두 개', '얼굴 무늬 안에 까만 눈을 두 개 그려요.', eyeL, eyeR);

  const beak = b.closed('beak', [[180, 200], [200, 194], [220, 200], [212, 212], [200, 220], [188, 212]], 0.7);
  b.step('부리', '두 눈 사이 아래에 작은 부리를 그려요.', beak);

  // 목도리 — 위아래 두 줄, 양 끝이 몸 테두리에 붙습니다.
  const scarfT = b.open('scarfT', [[78, 262], [140, 276], [200, 280], [260, 276], [322, 262]], ['body', 'body']);
  const scarfB = b.open('scarfB', [[70, 300], [140, 314], [200, 318], [260, 314], [330, 300]], ['body', 'body']);
  b.step('목도리', '얼굴 무늬 아래에 목도리 줄을 두 개 그어요.', scarfT, scarfB);

  // 목도리 끝자락 — 아래 끝에 술이 달린 짧은 띠
  const tail = b.open('tail', [
    [244, 316], [240, 344], [238, 372], [250, 380], [262, 372], [274, 380], [286, 370],
    [284, 340], [282, 312],
  ], ['scarfB', 'scarfB'], 0.8);
  b.step('목도리 끝', '목도리 오른쪽에 아래로 늘어진 끝자락을 그려요.', tail);

  // 흰 배 — 목도리 아래에서 내려와 둥글게 돌아 목도리 끝자락에 닿습니다.
  const belly = b.open('belly', [
    [140, 314], [116, 348], [112, 384], [134, 408], [176, 418], [220, 416],
    [254, 404], [262, 380],
  ], ['scarfB', 'tail']);
  b.step('흰 배', '목도리 아래에 둥근 흰 배를 그려요.', belly);

  const flipL = b.open('flipL', [[72, 318], [52, 336], [38, 366], [40, 386], [58, 384], [74, 364]], ['body', 'body']);
  const flipR = b.open('flipR', [[328, 318], [348, 336], [362, 366], [360, 386], [342, 384], [326, 364]], ['body', 'body']);
  b.step('날개 두 개', '몸 양옆에 아래로 뻗은 날개를 하나씩 그려요.', flipL, flipR);

  const footL = b.open('footL', [[136, 428], [120, 440], [116, 456], [134, 462], [154, 458], [170, 448], [172, 432]], ['body', 'body']);
  const footR = b.open('footR', [[264, 428], [280, 440], [284, 456], [266, 462], [246, 458], [230, 448], [228, 432]], ['body', 'body']);
  b.step('발 두 개', '몸 아래에 넓적한 발을 두 개 그려요.', footL, footR);

  const cheekL = b.closed('cheekL', ellipse(144, 208, 13, 8));
  const cheekR = b.closed('cheekR', ellipse(256, 208, 13, 8));
  b.step('볼 두 개', '부리 양옆에 발그레한 볼을 동그랗게 그려요.', cheekL, cheekR);

  return {
    id: 'penguin', title: '펭귄', theme: 'animal', difficulty: 'normal', grades: ['middle'],
    paper: 'portrait', viewBox: '0 0 400 500',
    setupSay: '종이를 세로로 놓고, 가운데에 손바닥만큼 크게 그릴 거예요.',
    coloringSeconds: 150, steps: b.steps, keywords: ['동물', '펭귄', '겨울'],
  };
}
