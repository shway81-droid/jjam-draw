import { bench } from './lib.mjs';

// ================================================================ 튤립 — 참조: refs/tulip.png
// 가운데 앞 꽃잎을 크게 먼저 긋고, 양옆 꽃잎·뒤 꽃잎 끝은 앞 꽃잎에 붙입니다.
export default function draw() {
  const b = bench();
  const front = b.closed('front', [
    [200, 224], [178, 219], [164, 200], [158, 160], [161, 118], [170, 86],
    [186, 68], [205, 62], [224, 68], [237, 90], [243, 128], [244, 166],
    [238, 200], [223, 219],
  ]);
  b.step('가운데 꽃잎', '종이 위쪽에 주먹만큼 길쭉한 꽃잎을 그려요.', front);

  const left = b.open('left', [
    [196, 224], [164, 220], [143, 206], [133, 182], [132, 150], [134, 110],
    [129, 70], [148, 70], [164, 82], [172, 95],
  ], ['front', 'front']);
  const right = b.open('right', [
    [204, 224], [236, 220], [257, 206], [267, 182], [268, 150], [262, 110],
    [266, 62], [246, 62], [230, 70],
  ], ['front', 'front']);
  b.step('옆 꽃잎', '가운데 꽃잎 양옆에 끝이 뾰족한 꽃잎을 붙여요.', left, right);

  const back = b.open('back', [[185, 70], [194, 56], [205, 48], [216, 56], [222, 69]], ['front', 'front'], 0.8);
  b.step('뒤 꽃잎', '가운데 꽃잎 위에 뾰족한 꽃잎 끝을 하나 더 그려요.', back);

  const stem = b.open('stem', [[193, 223], [193, 300], [195, 380], [196, 446], [212, 446], [210, 380], [208, 300], [207, 223]], ['front', 'front'], 0.6);
  b.step('긴 줄기', '꽃 아래로 길게 내려오는 줄기를 그려요.', stem);

  const leafL = b.open('leafL', [
    [196, 432], [166, 412], [142, 378], [128, 342], [124, 305],
    [150, 330], [174, 360], [194, 392],
  ], ['stem', 'stem'], 0.8);
  b.step('왼쪽 잎', '줄기 아래쪽 왼쪽에 길쭉한 잎을 그려요.', leafL);

  const leafR = b.open('leafR', [
    [210, 428], [238, 404], [258, 368], [270, 330], [274, 295],
    [246, 310], [224, 342], [209, 382],
  ], ['stem', 'stem'], 0.8);
  b.step('오른쪽 잎', '줄기 오른쪽에도 위로 뻗은 잎을 그려요.', leafR);

  return {
    id: 'tulip', title: '튤립', theme: 'plant', difficulty: 'easy', grades: ['lower'],
    paper: 'portrait', viewBox: '0 0 400 500',
    setupSay: '종이를 세로로 놓고, 위쪽에 주먹만큼 꽃잎부터 그릴 거예요.',
    coloringSeconds: 150, steps: b.steps, keywords: ['식물', '꽃', '봄'],
  };
}
