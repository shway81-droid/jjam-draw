import { bench, ellipse } from './lib.mjs';

// ================================================================ 버섯 — 참조: refs/mushroom.png
// 풀은 줄기 옆에서 나와 줄기로 돌아오는 뾰족뾰족한 한 획이라 끝이 뜨지 않습니다.
export default function draw() {
  const b = bench();
  const cap = b.closed('cap', [
    [200, 66], [256, 76], [304, 108], [338, 152], [356, 196], [356, 222], [340, 238],
    [300, 247], [250, 250], [200, 250], [150, 250], [100, 248], [62, 240], [44, 224],
    [44, 196], [62, 152], [96, 108], [144, 76],
  ]);
  b.step('둥근 갓', '종이 위쪽에 주먹만큼 크고 둥근 버섯 갓을 그려요.', cap);

  const under = b.open('under', [[52, 233], [100, 222], [160, 218], [200, 214], [250, 208], [300, 212], [348, 232]], ['cap', 'cap']);
  b.step('갓 아래 줄', '갓 아래쪽에 옆으로 길게 줄을 그어요.', under);

  const stem = b.open('stem', [
    [170, 250], [167, 290], [156, 336], [143, 382], [146, 418], [170, 432],
    [200, 434], [230, 432], [254, 418], [258, 382], [248, 336], [236, 290], [233, 250],
  ], ['cap', 'cap']);
  b.step('굵은 기둥', '갓 아래에 아래가 볼록한 굵은 기둥을 그려요.', stem);

  const s1 = b.closed('s1', ellipse(128, 120, 22, 19, 8, -0.3));
  const s2 = b.closed('s2', ellipse(194, 152, 23, 22));
  const s3 = b.closed('s3', ellipse(280, 156, 20, 21));
  b.step('큰 점 세 개', '갓 위에 동그란 점을 세 개 그려요.', s1, s2, s3);

  const s4 = b.closed('s4', ellipse(236, 92, 21, 15, 8, 0.15));
  const s5 = b.closed('s5', ellipse(176, 84, 12, 9));
  const s6 = b.closed('s6', ellipse(114, 182, 15, 15));
  b.step('작은 점 세 개', '큰 점 사이사이에 작은 점을 세 개 더 그려요.', s4, s5, s6);

  const gills = [[96, 84], [130, 122], [270, 278], [306, 316]].map(([xt, xb], i) => {
    const top = b.snap('under', [xt, 216]);
    const bot = b.snap('cap', [xb, 250]);
    return b.open(`g${i}`, [top, [(top[0] + bot[0]) / 2, (top[1] + bot[1]) / 2], bot], ['under', 'cap']);
  });
  b.step('갓 주름', '갓 아래 줄과 갓 끝 사이에 짧은 줄을 네 개 그어요.', ...gills);

  const grassL = b.open('grassL', [[150, 428], [124, 431], [100, 433], [94, 414], [86, 392], [100, 408], [112, 426], [112, 396], [116, 372], [124, 398], [130, 424], [134, 404], [140, 388]], ['stem', 'stem'], 0.5);
  const grassR = b.open('grassR', [[250, 428], [276, 431], [300, 433], [306, 414], [314, 392], [300, 408], [288, 426], [288, 396], [284, 372], [276, 398], [270, 424], [266, 404], [260, 388]], ['stem', 'stem'], 0.5);
  b.step('풀', '기둥 아래 양옆에 뾰족뾰족한 풀을 그려요.', grassL, grassR);

  return {
    id: 'mushroom', title: '버섯', theme: 'plant', difficulty: 'easy', grades: ['lower'],
    paper: 'portrait', viewBox: '0 0 400 500',
    setupSay: '종이를 세로로 놓고, 위쪽에 주먹만큼 큰 갓부터 그릴 거예요.',
    coloringSeconds: 150, steps: b.steps, keywords: ['식물', '버섯', '숲'],
  };
}
