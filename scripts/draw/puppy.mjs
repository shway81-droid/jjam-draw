import { bench, ellipse } from './lib.mjs';

// ================================================================ 강아지 — 참조: refs/puppy.png (앉아 있는 강아지, 정면)
// 눈썹·주둥이 줄·발가락 줄처럼 끝이 허공에 뜨는 선은 뺐고, 입은 코 아래 닫힌 웃는 입으로 바꿨습니다.
// 앞다리 안쪽 두 줄은 가슴에서 만나는 다리 사이 줄 하나로, 발가락은 몸 아래 둥근 혹으로 그립니다.
// 아래로 볼록한 반 동그라미를 n 개 잇는 점들(발가락) — owl.mjs 와 같은 모양입니다.
const cups = (x0, x1, y, n, h) => {
  const pts = [];
  const w = (x1 - x0) / n;
  for (let k = 0; k < n; k++) {
    for (let j = 0; j < 6; j++) {
      const t = (j / 6) * Math.PI;
      pts.push([x0 + w * k + (w / 2) * (1 - Math.cos(t)), y + h * Math.sin(t)]);
    }
  }
  pts.push([x1, y]);
  return pts;
};

