import { bench, ellipse } from './lib.mjs';

// ================================================================ 복주머니 — 참조: refs/lucky-bag.png
// 첫 획은 둥근 주머니와 위의 주름진 입구를 한 번에 두르는 테두리입니다.
// 참조에서 입구 위에 있던 매듭은 목(끈을 묶는 곳)으로 내렸고, 끈은 테두리 오목한 곳에서 매듭까지 잇습니다.
// 주머니의 떠 있는 주름 줄은 빼고, 앞에 닫힌 동그라미 복 무늬(안에 꽃)를 넣었습니다.

export default function draw() {
  const b = bench();
  const bag = b.closed('bag', [
    [170, 162], [138, 172], [100, 200], [68, 246], [48, 296], [44, 348], [55, 390],
    [86, 418], [134, 433], [200, 438], [266, 433], [314, 418], [345, 390], [356, 348],
    [352, 296], [332, 246], [300, 200], [262, 172], [232, 162],
    [248, 150], [266, 138], [282, 124], [292, 106], [285, 91], [270, 85], [258, 70], [242, 61],
    [226, 66], [213, 80], [201, 90], [189, 80], [176, 66], [160, 61], [144, 70], [132, 85],
    [117, 91], [110, 106], [120, 124], [136, 138], [154, 150],
  ], 0.9);
  b.step('복주머니', '종이 가운데에 위가 주름진 둥근 주머니를 크게 그려요.', bag);

  const knot = b.closed('knot', ellipse(201, 160, 19, 15, 10));
  const cordL = b.open('cordL', [[170, 162], [182, 160]], ['bag', 'knot']);
  const cordR = b.open('cordR', [[232, 162], [220, 160]], ['bag', 'knot']);
  b.step('끈과 매듭', '주머니 목에 끈을 두르고 가운데에 동그란 매듭을 지어요.', knot, cordL, cordR);

  const foldL = b.open('foldL', [[190, 147], [180, 120], [168, 96], [160, 66]], ['knot', 'bag']);
  const foldR = b.open('foldR', [[212, 147], [222, 120], [234, 96], [242, 66]], ['knot', 'bag']);
  b.step('주름', '매듭 위에서 주름진 입구 끝까지 주름을 두 줄 그어요.', foldL, foldR);

  const tailL = b.open('tailL', [[188, 170], [178, 208], [164, 250], [154, 286], [168, 294], [180, 290], [190, 254], [200, 212], [198, 175]], ['knot', 'knot'], 0.8);
  const tailR = b.open('tailR', [[214, 170], [224, 208], [238, 250], [248, 286], [234, 294], [222, 290], [212, 254], [204, 212], [204, 175]], ['knot', 'knot'], 0.8);
  b.step('늘어진 끈', '매듭 아래로 길게 늘어진 끈을 양쪽에 하나씩 그려요.', tailL, tailR);

  const badge = b.closed('badge', ellipse(200, 352, 46, 46, 12));
  b.step('복 동그라미', '끈 아래 주머니 가운데에 동그란 무늬를 그려요.', badge);

  const flower = b.closed('flower', Array.from({ length: 40 }, (_, i) => {
    const a = (i / 40) * Math.PI * 2 - Math.PI / 2;
    const r = 18 + 10 * Math.sqrt(Math.abs(Math.cos((a + Math.PI / 2) * 2.5)));
    return [200 + Math.cos(a) * r, 352 + Math.sin(a) * r];
  }), 0.6);
  b.step('꽃무늬', '동그라미 안에 꽃잎 다섯 개인 꽃을 그려요.', flower);

  return {
    id: 'lucky-bag', title: '복주머니', theme: 'season', difficulty: 'easy', grades: ['lower'],
    paper: 'portrait', viewBox: '0 0 400 500',
    setupSay: '종이를 세로로 놓고, 가운데에 손바닥만큼 크게 그릴 거예요.',
    coloringSeconds: 150, steps: b.steps, keywords: ['설날', '복주머니', '명절'],
  };
}
