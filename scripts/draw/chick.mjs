import { bench, ellipse } from './lib.mjs';

// ================================================================ 병아리 — 참조 없음(직접 디자인), 앞을 봅니다
// 머리와 몸이 하나로 이어진 통통한 물방울 몸을 첫 획으로 긋고, 나머지는 모두 몸에 붙입니다.
// 머리 위 깃털, 작은 날개, 세 갈래 발은 양 끝이 몸 테두리에 붙는 열린 획입니다.
export default function draw() {
  const b = bench();
  const body = b.closed('body', [
    [200, 112], [252, 120], [290, 150], [306, 196], [306, 240], [322, 282],
    [334, 330], [322, 378], [286, 408], [240, 422], [200, 424], [160, 422],
    [114, 408], [78, 378], [66, 330], [78, 282], [94, 240], [94, 196],
    [110, 150], [148, 120],
  ]);
  b.step('동그란 몸', '종이 가운데에 머리와 몸이 붙은 통통한 몸을 그려요.', body);

  const eyeL = b.closed('eyeL', ellipse(160, 214, 7, 9));
  const eyeR = b.closed('eyeR', ellipse(240, 214, 7, 9));
  b.step('눈 두 개', '몸 위쪽에 까맣고 동그란 눈을 두 개 그려요.', eyeL, eyeR);

  // 작은 부리 — 위가 넓고 아래가 뾰족한 둥근 세모
  const beak = b.closed('beak', [[184, 240], [200, 234], [216, 240], [208, 256], [200, 264], [192, 256]], 0.7);
  b.step('작은 부리', '두 눈 사이 아래에 뾰족한 작은 부리를 그려요.', beak);

  // 정수리 깃털 세 가닥 — 몸 꼭대기에서 나와 말려 올라갔다가 다시 몸으로 들어옵니다.
  const tuft = b.open('tuft', [
    [178, 116], [166, 92], [170, 72], [184, 80], [194, 98], [196, 70],
    [210, 60], [212, 82], [208, 102], [224, 84], [238, 88], [228, 106], [220, 116],
  ], ['body', 'body'], 0.8);
  b.step('머리 깃털', '머리 꼭대기에 쫑긋 솟은 깃털을 그려요.', tuft);

  const wingL = b.open('wingL', [[80, 284], [54, 286], [36, 302], [44, 318], [34, 336], [50, 352], [76, 356]], ['body', 'body'], 0.8);
  const wingR = b.open('wingR', [[320, 284], [346, 286], [364, 302], [356, 318], [366, 336], [350, 352], [324, 356]], ['body', 'body'], 0.8);
  b.step('작은 날개', '몸 양옆에 파닥이는 작은 날개를 하나씩 그려요.', wingL, wingR);

  // 세 갈래 발 — 몸 아래에서 내려와 발가락 세 개를 돌고 다시 몸으로 올라갑니다.
  const foot = (name, x) => b.open(name, [
    [x - 12, 422], [x - 12, 440], [x - 30, 450], [x - 26, 462], [x - 10, 456],
    [x, 466], [x + 10, 456], [x + 26, 462], [x + 30, 450], [x + 12, 440], [x + 12, 422],
  ], ['body', 'body'], 0.7);
  const footL = foot('footL', 160);
  const footR = foot('footR', 240);
  b.step('발 두 개', '몸 아래에 발가락이 세 개인 발을 두 개 그려요.', footL, footR);

  const cheekL = b.closed('cheekL', ellipse(132, 252, 16, 10));
  const cheekR = b.closed('cheekR', ellipse(268, 252, 16, 10));
  b.step('볼 두 개', '부리 양옆에 발그레한 볼을 동그랗게 그려요.', cheekL, cheekR);

  return {
    id: 'chick', title: '병아리', theme: 'animal', difficulty: 'easy', grades: ['lower'],
    paper: 'portrait', viewBox: '0 0 400 500',
    setupSay: '종이를 세로로 놓고, 가운데에 손바닥만큼 크게 그릴 거예요.',
    coloringSeconds: 150, steps: b.steps, keywords: ['동물', '병아리', '봄'],
  };
}
