import { bench, ellipse } from './lib.mjs';

// ================================================================ 아기 고래 — 참조 선화 없음(직접 디자인), 왼쪽을 봅니다
// 통통한 몸 하나에 배 줄과 배 주름, 지느러미, 위로 들린 꼬리, 머리 위 물줄기를 붙입니다.
// 배 주름은 양 끝이 배 줄과 몸 테두리에 닿고, 물줄기는 숨구멍에 붙은 닫힌 분수 모양입니다.
export default function draw() {
  const b = bench();
  const body = b.closed('body', [
    [170, 96], [230, 96], [290, 112], [345, 138], [392, 168], [420, 184],
    [424, 200], [408, 222], [370, 254], [315, 284], [250, 304], [180, 310],
    [118, 300], [76, 270], [54, 226], [56, 172], [78, 128], [118, 102],
  ]);
  b.step('통통한 몸', '종이 가운데에 앞이 둥글고 뒤가 가는 몸을 그려요.', body);

  const eye = b.closed('eye', ellipse(124, 182, 9, 11));
  b.step('눈', '몸 앞쪽에 작고 까만 눈을 그려요.', eye);

  const mouth = b.closed('mouth', [[76, 212], [100, 220], [126, 216], [120, 230], [100, 236], [84, 228]], 0.8);
  b.step('웃는 입', '눈 아래 몸 끝에 활짝 웃는 입을 그려요.', mouth);

  const cheek = b.closed('cheek', ellipse(158, 208, 13, 8));
  b.step('볼', '눈 옆 아래에 발그레한 볼을 작게 그려요.', cheek);

  const belly = b.open('belly', [[64, 256], [110, 258], [170, 256], [230, 250], [290, 244], [350, 230], [398, 212]], ['body', 'body']);
  b.step('배 줄', '입 아래에서 꼬리 쪽까지 배를 따라 줄을 그어요.', belly);

  const groove1 = b.open('gr1', [[80, 278], [140, 280], [210, 278], [264, 268], [300, 254], [322, 240]], ['body', 'belly']);
  const groove2 = b.open('gr2', [[112, 298], [160, 302], [210, 298], [246, 288], [268, 272]], ['body', 'gr1']);
  b.step('배 주름', '배 줄 아래에 배를 따라 주름을 두 줄 그어요.', groove1, groove2);

  const flipper = b.open('flipper', [[190, 254], [192, 230], [208, 214], [236, 214], [262, 228], [282, 246], [252, 248], [222, 254]], ['belly', 'belly']);
  b.step('지느러미', '배 줄 위에 둥근 지느러미를 그려요.', flipper);

  const fin = b.open('fin', [[262, 108], [282, 84], [298, 80], [304, 96], [306, 120]], ['body', 'body']);
  b.step('등지느러미', '등 위에 작고 둥근 지느러미를 그려요.', fin);

  const tail = b.open('tail', [
    [412, 178], [426, 152], [422, 124], [414, 98], [436, 96], [454, 112], [460, 126],
    [474, 100], [494, 88], [494, 114], [480, 144], [454, 176], [420, 206],
  ], ['body', 'body']);
  b.step('꼬리', '몸 끝에 위로 들린 꼬리를 두 갈래로 그려요.', tail);

  const tailLine = b.open('tailLine', [[460, 126], [448, 154], [430, 184]], ['tail', 'body']);
  b.step('꼬리 줄', '꼬리 가운데 갈라진 곳에서 몸까지 줄을 그어요.', tailLine);

  const top = b.snap('body', [176, 96]);
  const spout = b.closed('spout', [
    [top[0] - 11, top[1] + 1], [166, 78], [152, 72], [136, 76], [124, 88], [116, 78], [120, 62],
    [138, 52], [158, 54], [162, 40], [168, 28], [177, 24], [186, 28], [192, 40], [196, 54], [216, 52], [234, 62], [238, 78], [230, 88],
    [218, 76], [202, 72], [188, 78], [top[0] + 11, top[1]],
  ], 0.8);
  b.step('물줄기', '머리 위 숨구멍에서 솟는 물줄기를 그려요.', spout);

  const dropL = b.closed('dropL', [[98, 52], [104, 64], [100, 74], [90, 74], [88, 64]]);
  const dropR = b.closed('dropR', [[262, 50], [268, 62], [264, 72], [254, 72], [252, 62]]);
  b.step('물방울', '물줄기 양옆에 떨어지는 물방울을 두 개 그려요.', dropL, dropR);

  const bubbles = [[30, 186, 11], [30, 146, 8], [44, 114, 6]].map(([x, y, r], k) => b.closed(`bub${k}`, ellipse(x, y, r, r)));
  b.step('거품', '얼굴 앞에 크고 작은 거품을 세 개 그려요.', ...bubbles);

  return {
    id: 'whale', title: '고래', theme: 'animal', difficulty: 'hard', grades: ['upper'],
    paper: 'landscape', viewBox: '0 0 500 400',
    setupSay: '종이를 가로로 놓고, 가운데에 손바닥만큼 큰 몸부터 그릴 거예요.',
    coloringSeconds: 180, steps: b.steps, keywords: ['동물', '고래', '바다'],
  };
}
