import { bench, ellipse } from './lib.mjs';

// ================================================================ 비행기 — 참조 없음(직접 디자인), 오른쪽으로 나는 통통한 여객기
const cloud = (cx, cy, s) => [
  [-50, 12], [-56, 0], [-46, -12], [-32, -12], [-26, -26], [-10, -34], [8, -30],
  [18, -18], [32, -22], [48, -12], [54, 2], [46, 14], [24, 17], [0, 17], [-26, 17],
].map(([x, y]) => [cx + x * s, cy + y * s]);

export default function draw() {
  const b = bench();
  const body = b.closed('body', [
    [380, 136], [418, 150], [440, 178], [444, 210], [430, 240], [400, 260],
    [350, 272], [270, 276], [200, 272], [150, 258], [112, 232], [86, 196],
    [76, 160], [84, 138], [120, 134], [200, 133], [300, 133],
  ]);
  b.step('통통한 몸통', '종이 가운데에 앞이 둥글고 뒤가 올라간 긴 몸통을 그려요.', body);

  const cockpit = b.closed('cockpit', [[392, 158], [414, 164], [428, 180], [432, 196], [410, 199], [390, 195], [384, 176]], 0.8);
  b.step('조종석 창', '몸통 앞쪽 위에 조종사가 보는 둥근 창을 그려요.', cockpit);

  const wins = [200, 238, 276, 314, 352].map((x, i) => b.closed(`w${i}`, ellipse(x, 184, 13, 14)));
  b.step('동그란 창 다섯 개', '조종석 창 뒤로 작고 동그란 창을 줄지어 다섯 개 그려요.', ...wins);

  const door = b.closed('door', [[140, 168], [152, 160], [164, 168], [164, 232], [152, 240], [140, 232]], 0.7);
  b.step('문', '창 뒤쪽 끝에 위아래가 둥근 길쭉한 문을 그려요.', door);

  const line = b.open('line', [[440, 226], [380, 228], [300, 228], [220, 226], [164, 224]], ['body', 'door']);
  b.step('몸통 줄무늬', '몸통 앞에서 문까지 창 아래로 긴 줄을 그어요.', line);

  const fin = b.open('fin', [[90, 136], [78, 100], [68, 66], [74, 50], [96, 48], [120, 78], [150, 116], [180, 133]], ['body', 'body']);
  b.step('꼬리 날개', '몸통 뒤 끝 위로 높이 솟은 꼬리 날개를 그려요.', fin);

  const finLine = b.open('finLine', [[74, 86], [94, 88], [112, 82]], ['fin', 'fin']);
  b.step('꼬리 무늬', '꼬리 날개 위쪽을 가로지르는 줄을 하나 그어요.', finLine);

  const tailWing = b.open('tailWing', [[104, 226], [72, 236], [42, 240], [30, 228], [40, 214], [72, 208], [92, 206]], ['body', 'body']);
  b.step('작은 뒷날개', '몸통 꼬리 끝 옆에 작고 납작한 날개를 그려요.', tailWing);

  const wing = b.open('wing', [[320, 272], [290, 302], [244, 340], [204, 364], [178, 368], [168, 352], [184, 326], [210, 298], [232, 274]], ['body', 'body']);
  b.step('큰 날개', '몸통 가운데 아래로 뒤쪽을 향한 큰 날개를 그려요.', wing);

  const flap = b.open('flap', [[196, 324], [214, 332], [232, 336]], ['wing', 'wing']);
  b.step('날개 줄', '날개 안쪽에 짧게 비스듬한 줄을 하나 그어요.', flap);

  const engine = b.open('engine', [[294, 296], [330, 296], [350, 306], [352, 322], [336, 334], [300, 334], [262, 322]], ['wing', 'wing']);
  b.step('엔진', '날개 아래 앞쪽에 통통한 엔진을 매달아 그려요.', engine);

  const intake = b.open('intake', [[338, 299], [330, 315], [338, 332]], ['engine', 'engine']);
  b.step('엔진 입구', '엔진 앞쪽 끝에 둥근 입구 줄을 그어요.', intake);

  const c1 = b.closed('c1', cloud(430, 340, 0.85), 0.9);
  b.step('구름 하나', '날개 오른쪽 아래에 몽실몽실한 구름을 그려요.', c1);

  const c2 = b.closed('c2', cloud(260, 66, 0.8), 0.9);
  b.step('구름 둘', '몸통 위 빈 곳에 작은 구름을 하나 더 그려요.', c2);

  return {
    id: 'airplane', title: '비행기', theme: 'thing', difficulty: 'hard', grades: ['upper'],
    paper: 'landscape', viewBox: '0 0 500 400',
    setupSay: '종이를 가로로 놓고, 가운데에 손바닥만큼 긴 몸통부터 그릴 거예요.',
    coloringSeconds: 180, steps: b.steps, keywords: ['탈것', '비행기', '하늘'],
  };
}
