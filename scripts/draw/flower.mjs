import { bench, ellipse, smooth } from './lib.mjs';
import { sample } from '../path-geom.mjs';

// 꽃잎 하나하나를 오목한 곳에서 오목한 곳까지 부드럽게 이은 뒤 촘촘한 점으로 바꿉니다 —
// 이렇게 이으면 꽃잎은 둥글고 꽃잎 사이는 오목하게 꺾입니다.
const ring = (arcs) => arcs.flatMap((a) => sample(smooth(a, false, 1), 3).slice(0, -1))
  .filter((p, i, all) => i === 0 || Math.hypot(p[0] - all[i - 1][0], p[1] - all[i - 1][1]) > 1.5);

// ================================================================ 꽃 한 송이 — 참조: refs/flower.png
// 꽃잎 아홉 장의 바깥 테두리를 한 획으로 먼저 긋고(첫 획이 크기를 정함), 가운데 동그라미에서
// 꽃잎 사이 오목한 곳까지 선을 그어 꽃잎을 나눕니다. 꽃잎은 가운데로 갈수록 좁아지는 물방울 모양이 됩니다.
const C = [201, 147];
// 꽃잎 사이 오목한 곳(바깥 테두리 위) — 위 가운데에서 시계 방향
const V = [
  [229, 86], [262, 120], [262, 165], [248, 204], [218, 209], [168, 202], [150, 162], [134, 112], [177, 79],
];

export default function draw() {
  const b = bench();
  const petals = b.closed('petals', ring([
    [V[8], [181, 64], [193, 53], [208, 50], [223, 55], [232, 69], V[0]], // 위
    [V[0], [244, 77], [260, 72], [274, 80], [279, 96], [272, 112], V[1]], // 오른쪽 위
    [V[1], [280, 117], [294, 124], [300, 140], [295, 157], [280, 165], V[2]], // 오른쪽
    [V[2], [278, 175], [287, 190], [281, 203], [265, 208], V[3]], // 오른쪽 아래
    [V[3], [247, 217], [238, 227], [225, 227], V[4]], // 아래 작은 꽃잎
    [V[4], [217, 223], [208, 233], [193, 236], [178, 231], [168, 218], V[5]], // 아래
    [V[5], [154, 208], [136, 210], [121, 200], [116, 184], [124, 170], V[6]], // 왼쪽 아래
    [V[6], [127, 163], [110, 155], [101, 140], [106, 122], [120, 113], V[7]], // 왼쪽
    [V[7], [128, 98], [127, 82], [139, 70], [156, 66], [170, 70], V[8]], // 왼쪽 위
  ]), 0.5);
  b.step('꽃잎 테두리', '종이 위쪽에 꽃잎이 둥글게 돌아가는 큰 꽃을 그려요.', petals);

  const center = b.closed('center', ellipse(C[0], C[1], 28, 27));
  b.step('꽃 가운데', '꽃 한가운데에 동그라미를 하나 그려요.', center);

  // 가운데 동그라미에서 꽃잎 사이 오목한 곳까지
  const line = (i) => {
    const v = V[i];
    const dx = v[0] - C[0]; const dy = v[1] - C[1]; const l = Math.hypot(dx, dy);
    const a = [C[0] + (dx / l) * 27, C[1] + (dy / l) * 27];
    const m = [(a[0] + v[0]) / 2, (a[1] + v[1]) / 2];
    return b.open(`l${i}`, [a, m, v], ['center', 'petals']);
  };
  const top = [7, 8, 0, 1].map(line);
  b.step('위쪽 꽃잎', '가운데 동그라미에서 위쪽 꽃잎 사이로 줄을 그어요.', ...top);
  const bottom = [2, 3, 4, 5, 6].map(line);
  b.step('아래쪽 꽃잎', '가운데 동그라미에서 아래쪽 꽃잎 사이로 줄을 그어요.', ...bottom);

  // 꽃 아래에서 내려오는 가는 줄기 — 내려갔다가 바닥에서 돌아 다시 꽃까지 올라옵니다.
  const stem = b.open('stem', [
    [193, 235], [194, 290], [192, 350], [191, 410], [192, 448], [201, 449],
    [208, 447], [204, 410], [204, 350], [206, 290], [207, 234],
  ], ['petals', 'petals']);
  b.step('줄기', '꽃 아래에서 길게 내려오는 줄기를 그려요.', stem);

  // 잎은 줄기에서 나와 끝이 뾰족하게 돌아 다시 줄기로 들어옵니다.
  const leafL = b.open('leafL', [
    [193, 320], [174, 318], [152, 311], [135, 295], [120, 268], [146, 266],
    [170, 278], [186, 296], [193, 310],
  ], ['stem', 'stem'], 0.8);
  const leafR = b.open('leafR', [
    [206, 336], [220, 312], [240, 295], [262, 286], [282, 284], [273, 305],
    [256, 326], [234, 339], [206, 342],
  ], ['stem', 'stem'], 0.8);
  b.step('잎 두 개', '줄기 양옆에 끝이 뾰족한 잎을 하나씩 그려요.', leafL, leafR);

  const veinL = b.open('veinL', [[193, 316], [160, 292], [124, 270]], ['stem', 'leafL']);
  const veinR = b.open('veinR', [[206, 339], [244, 312], [278, 287]], ['stem', 'leafR']);
  b.step('잎맥', '잎 가운데에 줄기에서 잎 끝까지 줄을 그어요.', veinL, veinR);

  return {
    id: 'flower', title: '꽃 한 송이', theme: 'plant', difficulty: 'easy', grades: ['lower'],
    paper: 'portrait', viewBox: '0 0 400 500',
    setupSay: '종이를 세로로 놓고, 위쪽에 주먹만큼 크게 꽃을 그릴 거예요.',
    coloringSeconds: 120, steps: b.steps, keywords: ['식물', '꽃', '봄'],
  };
}
