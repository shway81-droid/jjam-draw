import { bench, ellipse } from './lib.mjs';

// ================================================================ 화분 선인장 — 참조: refs/cactus.png
// 가시는 짧은 닫힌 모양으로 바꿨고, 몸통 가운데에 작은 얼굴을 넣었습니다.
export default function draw() {
  const b = bench();
  const rim = b.closed('rim', [
    [106, 298], [112, 287], [150, 282], [200, 281], [250, 282], [288, 287],
    [294, 298], [288, 309], [250, 313], [200, 314], [150, 313], [112, 309],
  ]);
  const pot = b.open('pot', [
    [114, 310], [118, 352], [128, 400], [146, 436], [200, 447], [254, 436],
    [272, 400], [282, 352], [286, 310],
  ], ['rim', 'rim']);
  b.step('화분', '종이 아래쪽에 테두리가 있는 큰 화분을 그려요.', rim, pot);

  const body = b.open('body', [
    [170, 282], [164, 258], [158, 232], [150, 212], [138, 190], [132, 160],
    [132, 130], [140, 106], [156, 84], [176, 70], [200, 64], [224, 70],
    [244, 84], [258, 108], [264, 140], [258, 168], [248, 192], [242, 222],
    [238, 252], [232, 282],
  ], ['rim', 'rim']);
  b.step('긴 몸통', '화분 위에 위가 둥근 긴 몸통을 그려요.', body);

  const eyeL = b.closed('eyeL', ellipse(186, 168, 6, 7));
  const eyeR = b.closed('eyeR', ellipse(214, 168, 6, 7));
  b.step('눈 두 개', '몸통 가운데에 작은 눈을 두 개 그려요.', eyeL, eyeR);

  const mouth = b.closed('mouth', [[190, 186], [200, 188], [210, 186], [207, 194], [200, 198], [193, 194]]);
  b.step('웃는 입', '눈 사이 아래에 작게 웃는 입을 그려요.', mouth);

  const armL = b.open('armL', [
    [150, 210], [136, 192], [120, 176], [102, 174], [90, 190], [90, 212],
    [102, 232], [122, 243], [146, 244], [162, 244],
  ], ['body', 'body']);
  b.step('왼쪽 팔', '몸통 왼쪽에 동그랗게 올라간 팔을 그려요.', armL);

  const armR = b.open('armR', [
    [249, 190], [256, 166], [268, 146], [288, 136], [306, 144], [314, 166],
    [308, 192], [292, 210], [268, 218], [242, 218],
  ], ['body', 'body']);
  b.step('오른쪽 팔', '몸통 오른쪽에도 동그란 팔을 하나 그려요.', armR);

  const ridgeL = b.open('ridgeL', [[200, 64], [176, 100], [164, 150], [166, 210], [176, 252], [186, 282]], ['body', 'rim']);
  const ridgeR = b.open('ridgeR', [[200, 64], [224, 100], [236, 150], [234, 210], [224, 252], [214, 282]], ['body', 'rim']);
  b.step('몸통 줄 두 개', '몸통 꼭대기에서 화분까지 줄을 두 개 그어요.', ridgeL, ridgeR);

  const armLr = b.open('armLr', [[108, 174], [108, 200], [122, 224], [140, 244]], ['armL', 'armL']);
  const armRr = b.open('armRr', [[292, 137], [278, 160], [270, 190], [272, 216]], ['armR', 'armR']);
  b.step('팔 줄 두 개', '팔 위에서 아래까지 줄을 하나씩 그어요.', armLr, armRr);

  // 가시는 끝이 뜨지 않게 테두리에 붙은 작고 가는 닫힌 모양으로 바꿨습니다.
  const spines = [[160, 70, -0.64], [250, 78, 0.78], [123, 130, -1.57], [269, 110, 1.3], [317, 145, 1.0], [81, 200, -1.57]]
    .map(([x, y, r], k) => b.closed(`spine${k}`, ellipse(x, y, 2.5, 8, 8, r)));
  b.step('작은 가시', '몸통과 팔 둘레에 짧은 가시를 콕콕 그려요.', ...spines);

  const dots = [[140, 345], [200, 340], [262, 345], [150, 392], [222, 396]].map(([x, y]) => b.closed(`dot${x}`, ellipse(x, y, 10, 10)));
  b.step('화분 무늬', '화분에 작은 동그라미 무늬를 몇 개 그려요.', ...dots);

  return {
    id: 'cactus', title: '화분 선인장', theme: 'plant', difficulty: 'normal', grades: ['middle'],
    paper: 'portrait', viewBox: '0 0 400 500',
    setupSay: '종이를 세로로 놓고, 아래쪽에 손바닥만큼 큰 화분부터 그릴 거예요.',
    coloringSeconds: 150, steps: b.steps, keywords: ['식물', '선인장', '화분'],
  };
}
