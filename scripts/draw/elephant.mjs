import { bench, ellipse } from './lib.mjs';

// ================================================================ 아기 코끼리 — 참조: refs/elephant.png, 왼쪽을 봅니다
// 참조의 눈썹·코 주름 잔선은 끝이 떠서 빼고, 코 주름은 양 끝이 코 테두리에 닿게 바꿨습니다.
// 벌린 입은 코와 겹쳐 복잡해서 빼고 발그레한 볼을 넣었습니다. 코끝은 앞으로 살짝 말려 올라가게 했습니다.
const DX = 10;
const T = (pts) => pts.map(([x, y]) => [x + DX, y]);

export default function draw() {
  const b = bench();
  // 머리와 코를 한 번에 — 이마 앞선이 그대로 내려와 코가 됩니다(참조와 같은 옆모습).
  const head = b.closed('head', T([
    [175, 54], [214, 60], [238, 84], [248, 124], [244, 168], [228, 204],
    [200, 226], [170, 236], [146, 238], [126, 246], [112, 262], [102, 282],
    [90, 300], [74, 310], [56, 308], [44, 296], [44, 282], [54, 276],
    [66, 274], [76, 260], [82, 236], [86, 204], [89, 170], [93, 136],
    [104, 102], [124, 74], [148, 59],
  ]));
  b.step('머리와 코', '종이 왼쪽 가운데에 긴 코가 달린 큰 머리를 그려요.', head);

  const eye = b.closed('eye', ellipse(174 + DX, 154, 8, 10));
  b.step('눈', '머리 가운데에 작고 까만 눈을 그려요.', eye);

  const ear = b.open('ear', T([
    [222, 62], [254, 48], [292, 52], [316, 80], [318, 126], [310, 170],
    [292, 198], [264, 210], [238, 202],
  ]), ['head', 'head']);
  b.step('큰 귀', '머리 오른쪽에 손바닥만큼 넓은 귀를 그려요.', ear);

  const earIn = b.open('earIn', T([[247, 104], [264, 82], [290, 84], [304, 112], [304, 152], [290, 180], [266, 194], [250, 200]]), ['head', 'ear']);
  b.step('귀 안쪽', '귀 안쪽을 따라 줄을 하나 더 그려요.', earIn);

  const wr1 = b.open('wr1', T([[80, 252], [96, 256], [112, 262]]), ['head', 'head']);
  const wr2 = b.open('wr2', T([[68, 278], [84, 284], [98, 290]]), ['head', 'head']);
  b.step('코 주름', '코를 가로질러 짧은 주름을 두 개 그어요.', wr1, wr2);

  const mouth = b.closed('mouth', T([[146, 204], [158, 208], [170, 205], [166, 214], [157, 219], [149, 214]]));
  b.step('웃는 입', '코 옆 아래에 작게 웃는 입을 그려요.', mouth);

  const cheek = b.closed('cheek', ellipse(204 + DX, 184, 11, 7));
  b.step('볼', '눈 옆 아래에 발그레한 볼을 작게 그려요.', cheek);

  const body = b.open('body', T([
    [312, 76], [350, 86], [382, 112], [398, 158], [398, 208], [388, 248],
    [370, 272], [340, 284], [300, 290], [262, 288], [228, 276], [206, 254], [198, 232],
  ]), ['ear', 'head']);
  b.step('통통한 몸', '귀 뒤에서 머리 밑까지 둥근 몸을 그려요.', body);

  const legF = b.open('legF', T([[208, 260], [206, 300], [204, 336], [210, 354], [232, 360], [254, 356], [260, 332], [258, 300], [256, 284]]), ['body', 'body']);
  const legB = b.open('legB', T([[338, 284], [334, 320], [334, 346], [344, 358], [366, 360], [382, 348], [386, 300], [388, 250]]), ['body', 'body']);
  b.step('앞다리', '머리 아래에 짧고 통통한 앞다리를 그려요.', legF);
  b.step('뒷다리', '몸 뒤쪽 아래에 똑같이 통통한 뒷다리를 그려요.', legB);

  const legF2 = b.open('legF2', T([[186, 238], [178, 280], [174, 320], [178, 342], [192, 348], [206, 346]]), ['body', 'legF']);
  const legB2 = b.open('legB2', T([[298, 290], [294, 318], [296, 338], [310, 346], [334, 344]]), ['body', 'legB']);
  b.step('안쪽 다리', '다리 뒤로 살짝 보이는 다리를 두 개 더 그려요.', legF2, legB2);

  const toes = [[220, 352], [242, 352], [350, 352], [370, 352]].map(([x, y], k) => b.closed(`toe${k}`, ellipse(x + DX, y, 7, 6)));
  b.step('발톱', '발 아래에 둥근 발톱을 두 개씩 그려요.', ...toes);

  const tuft = b.closed('tuft', T([[420, 288], [430, 296], [434, 310], [424, 306], [416, 314], [414, 300]]));
  const tail = b.open('tail', T([[396, 214], [410, 236], [418, 262], [421, 290]]), ['body', 'tuft']);
  b.step('꼬리', '몸 뒤에 털 뭉치를 그리고 꼬리로 이어요.', tuft, tail);

  const hair = b.bumps('hair', 'head', [150 + DX, 56], [196 + DX, 56], 2, 13, 1, true);
  b.step('머리털', '머리 꼭대기에 동글동글한 털을 그려요.', hair);

  return {
    id: 'elephant', title: '코끼리', theme: 'animal', difficulty: 'hard', grades: ['upper'],
    paper: 'landscape', viewBox: '0 0 500 400',
    setupSay: '종이를 가로로 놓고, 왼쪽에 주먹만큼 큰 머리부터 그릴 거예요.',
    coloringSeconds: 180, steps: b.steps, keywords: ['동물', '코끼리', '동물원'],
  };
}
